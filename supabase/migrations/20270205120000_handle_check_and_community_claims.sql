-- ── 4 · the claim row as her profile reads it ───────────────────────────────────
create or replace function public._community_claim_row(c public.place_claims)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select jsonb_build_object(
    'claim_id', c.id,
    'reference', 'CL-' || c.reference_no::text,
    'place_id', c.place_id,
    'place_name', p.name,
    'place_type', p.place_type,
    'status', case
                when c.status = 'verified' then 'approved'
                when c.status = 'rejected' then 'declined'
                else 'pending'
              end,
    'reviewer_note', case when c.status in ('verified', 'rejected') then c.review_notes end,
    'decided_at', case when c.status in ('verified', 'rejected') then c.resolved_at end,
    'submitted_at', c.submitted_at
  )
  from public.places p
  where p.id = c.place_id;
$$;

revoke all on function public._community_claim_row(public.place_claims) from public, anon, authenticated;

-- ── 5 · submit ──────────────────────────────────────────────────────────────────
-- Raises (P0001) with the word the client branches on:
--   no_such_place · already_claimed (someone governs it) · already_yours (she already
--   runs it) · claim_open (an open claim on the place, or she has one of her own).
create or replace function public.submit_community_claim_for(
  p_user_id       uuid,
  p_place_id      uuid,
  p_contact_email text,
  p_contact_phone text default null,
  p_note          text default null,
  p_proof_path    text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_gov text;
  c     public.place_claims;
begin
  if p_user_id is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;

  select governance_state into v_gov from public.places where id = p_place_id for update;
  if v_gov is null then
    raise exception 'no_such_place' using errcode = 'P0001';
  end if;
  if v_gov in ('operator_verified', 'suspended') then
    raise exception 'already_claimed' using errcode = 'P0001';
  end if;
  if exists (select 1 from public.places where id = p_place_id and created_by = p_user_id)
     or exists (select 1 from public.place_managers m
                 where m.place_id = p_place_id and m.user_id = p_user_id
                   and m.role = 'operator' and m.removed_at is null) then
    raise exception 'already_yours' using errcode = 'P0001';
  end if;

  -- One at a time for her: a pending claim, or a declined one she has not closed yet.
  -- An approved claim does not hold the slot — the profile hides it once it is approved.
  -- Serialize her submits so two taps cannot both pass this check.
  perform pg_advisory_xact_lock(hashtext('community_claim:' || p_user_id::text));
  if exists (
    select 1 from public.place_claims x
     where x.requested_by = p_user_id and x.origin = 'in_app' and x.closed_at is null
       and x.status in ('draft', 'pending_verification', 'needs_more_info', 'rejected')
  ) then
    raise exception 'claim_open' using errcode = 'P0001';
  end if;

  begin
    insert into public.place_claims (
      place_id, requested_by, status, verification_method, origin,
      contact_email, contact_phone, claim_note, evidence_storage_path, submitted_at
    ) values (
      p_place_id, p_user_id, 'pending_verification', 'manual_review', 'in_app',
      p_contact_email, p_contact_phone, p_note, p_proof_path, now()
    )
    returning * into c;
  exception
    -- place_claims_one_open_per_place: someone (website or app) already has it open.
    when unique_violation then
      raise exception 'claim_open' using errcode = 'P0001';
  end;

  -- Same as save_place_claim: governance shows the claim is pending; nothing members
  -- built on the place is touched. reject_place_claim reverts this.
  if v_gov = 'community_started' then
    update public.places set governance_state = 'claim_pending' where id = p_place_id;
  end if;

  return public._community_claim_row(c);
end;
$$;

-- ── 6 · her claims ──────────────────────────────────────────────────────────────
create or replace function public.my_community_claims_for(p_user_id uuid)
returns jsonb
language sql
stable
security definer
set search_path = pg_catalog, public
as $$
  select coalesce(jsonb_agg(public._community_claim_row(c) order by c.created_at desc), '[]'::jsonb)
    from public.place_claims c
   where c.requested_by = p_user_id
     and c.origin = 'in_app'
     and c.closed_at is null
     and c.status in ('pending_verification', 'needs_more_info', 'verified', 'rejected');
$$;

-- ── 7 · close ───────────────────────────────────────────────────────────────────
-- Only her own, only once decided, idempotent. Raises no_such_claim / not_decided.
create or replace function public.close_community_claim_for(p_user_id uuid, p_claim_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  c public.place_claims;
begin
  select * into c from public.place_claims
   where id = p_claim_id and requested_by = p_user_id and origin = 'in_app'
   for update;
  if c.id is null then
    raise exception 'no_such_claim' using errcode = 'P0001';
  end if;
  if c.status not in ('verified', 'rejected') then
    raise exception 'not_decided' using errcode = 'P0001';
  end if;
  if c.closed_at is null then
    update public.place_claims set closed_at = now() where id = c.id;
  end if;
  return jsonb_build_object('claim_id', c.id, 'closed', true);
end;
$$;

revoke all on function public.submit_community_claim_for(uuid, uuid, text, text, text, text)
  from public, anon, authenticated;
revoke all on function public.my_community_claims_for(uuid) from public, anon, authenticated;
revoke all on function public.close_community_claim_for(uuid, uuid) from public, anon, authenticated;
grant execute on function public.submit_community_claim_for(uuid, uuid, text, text, text, text)
  to service_role;
