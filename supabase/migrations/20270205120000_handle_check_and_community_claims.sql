-- Lana · Profile nickname check + claiming a community from the app ──────────────
-- Two backend asks, one migration because neither is big enough to stand alone.
--
-- §63 check_my_handle — the profile's nickname field checks "is it free?" while she
--   types. set_my_handle writes on success, so it cannot be called per keystroke, and
--   check_community_handle runs the PLACE shape rules first (a hyphen-free word comes
--   back single_token_requires_identity before users.handle is ever consulted).
--   This is set_my_handle's own rules, read-only.
--
-- §62 In-app community claims — the real owner of a community already on Lana asks for
--   it from her profile. Until now every door into place_claims was the lana-help
--   website's reservation flow (save_place_claim needs an active p_token_hash), with no
--   contact or note, nothing to read your own claims back, and nothing to close one.
--   Same table, so the admin portal's review queue and approve_place_claim /
--   reject_place_claim work on these rows unchanged. What is new:
--     · origin            'website' | 'in_app' — which door the claim came through. Only
--                         in-app claims show on a profile, count toward her one-open
--                         limit, or get a decision notice from the worker.
--     · contact_email / contact_phone / claim_note — what the claimant told the reviewer.
--     · evidence_storage_path (existing) carries the proof photo, in a PRIVATE bucket.
--     · reference_no      the number support quotes back ("CL-1042").
--     · closed_at         she dismissed a decided claim; it leaves her profile.
--     · decision_notified_at — the worker told her about the decision (idempotency).
--   The functions are service_role only: the worker authenticates the caller, then calls
--   them with her id. RLS on place_claims stays select-less for clients.

-- ── 1 · check_my_handle ─────────────────────────────────────────────────────────
create or replace function public.check_my_handle(p_handle text)
returns jsonb
language plpgsql
stable
-- DEFINER, unlike set_my_handle: a check that RLS can blind to another user's row would
-- say "available" and the save would then say taken. Returns a status only, never who.
security definer
set search_path = pg_catalog, public
as $$
declare
  v_handle text := lower(btrim(coalesce(p_handle, '')));
begin
  if auth.uid() is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  if v_handle !~ '^[a-z0-9]{3,20}$' then
    return jsonb_build_object('status', 'invalid', 'handle', v_handle);
  end if;
  if exists (select 1 from public.users u where u.id = auth.uid() and u.handle = v_handle) then
    return jsonb_build_object('status', 'unchanged', 'handle', v_handle);
  end if;
  if exists (select 1 from public.users u where u.handle = v_handle)
     or public.handle_held_by_place(v_handle) then
    return jsonb_build_object('status', 'taken', 'handle', v_handle);
  end if;
  return jsonb_build_object('status', 'available', 'handle', v_handle);
end;
$$;

revoke all on function public.check_my_handle(text) from public, anon;
grant execute on function public.check_my_handle(text) to authenticated;

comment on function public.check_my_handle(text) is
  'Read-only twin of set_my_handle for the profile editor (backend-asks §63): '
  '{status: available|taken|invalid|unchanged, handle}. Same rules — ^[a-z0-9]{3,20}$, '
  'unique across users.handle and places (handle_held_by_place). Writes nothing.';

