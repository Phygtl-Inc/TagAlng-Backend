-- Existing rows get numbers too; harmless, and the portal can show them for every claim.
alter table public.place_claims
  add column if not exists reference_no bigint generated by default as identity (start with 1001);
create unique index if not exists place_claims_reference_no_uniq
  on public.place_claims (reference_no);

-- Her profile list: her in-app claims, not yet closed.
create index if not exists place_claims_in_app_mine_idx
  on public.place_claims (requested_by, created_at desc)
  where origin = 'in_app' and closed_at is null;

-- The decision-notice sweep: decided in-app claims nobody has told her about.
create index if not exists place_claims_decision_unnotified_idx
  on public.place_claims (resolved_at)
  where origin = 'in_app' and decision_notified_at is null
    and status in ('verified', 'rejected');

